/**
 * Flavor Tree — единственное место, где меняется адрес бэкенда.
 *
 * Печатный QR не может нести «?api=...» — гость его не поправит. Поэтому
 * адрес API задаётся здесь, до загрузки api.js, и уезжает вместе со статикой.
 *
 * Пустая строка = API на том же домене, что и страница (прод за одним
 * доменом или reverse proxy). Иначе — полный https-адрес бэкенда.
 */
(function (global) {
  'use strict';

  // ⬇️ ЕДИНСТВЕННАЯ СТРОКА ДЛЯ ПРАВКИ ПЕРЕД ПЕЧАТЬЮ QR
  var API = '';

  // Локальная разработка: статика на 5500, Django на 8000 — не мешаем себе руками
  var isLocal = /^(localhost|127\.0\.0\.1|0\.0\.0\.0|\[::1\])$/.test(location.hostname);
  if (!API && isLocal && location.port !== '8000') API = 'http://127.0.0.1:8000';

  // ?api=... остаётся для отладки и всегда старше конфига (см. api.js)
  if (API) global.FT_API_BASE = API;
})(window);
